export function outputs() {
  return {
    [OUT.pluginJs]: pluginScript(),
    [OUT.pluginCss]: read(join(SRC, "contribution-workflow.css")),
    [OUT.demo]: demoHtml(),
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, content] of Object.entries(outputs())) {
    const now = existsSync(file) ? read(file) : null;
    if (check) { if (now !== content) { stale++; console.log(`out of date: ${file}`); } continue; }
    writeFileSync(file, content);
    console.log(`wrote ${file} (${content.length} chars)`);
  }
  if (check && stale) process.exit(1);
}
