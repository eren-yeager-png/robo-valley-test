#!/usr/bin/env node
// Builds everything that is GENERATED from the contribution workflow's source files (public/cw), so nothing is ever hand-copied:
//   frontend/wordpress/plugins/robovalley-contribution/assets/js/robovalley-contribution.js   the WordPress screens, as ONE script
//   frontend/wordpress/plugins/robovalley-contribution/assets/css/contribution-workflow.css  a byte-identical copy of the stylesheet
//   frontend/wordpress/plugins/robovalley-contribution/assets/js/rv-sector.js              the sector pages: header button + field buttons
//   frontend/wordpress/plugins/robovalley-contribution/assets/css/rv-sector.css            their stylesheet (a byte-identical copy)
//   docs/reference/contribution_demo.html                                                  the standalone demo (double-click, no server)
// The ES modules are joined by a tiny module bundler (each module keeps its own scope), so one versioned file is served: imports
// between ES modules would not carry the plugin's ?ver= and could be served stale after an update. tests/cw-build.test.ts checks
// that the committed files are exactly what this script produces.
// usage: node scripts/build-contribution-workflow.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "public", "cw");
const PLUGIN = join(ROOT, "frontend", "wordpress", "plugins", "robovalley-contribution");
const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");
export const OUT = {
  pluginJs: join(PLUGIN, "assets", "js", "robovalley-contribution.js"),
  pluginCss: join(PLUGIN, "assets", "css", "contribution-workflow.css"),
  sectorJs: join(PLUGIN, "assets", "js", "rv-sector.js"),
  sectorCss: join(PLUGIN, "assets", "css", "rv-sector.css"),
  demo: join(ROOT, "docs", "reference", "contribution_demo.html"),
};

/** One ES module as a scoped function: `import`s become lookups, `export`s are collected. Only the forms our sources use are allowed. */
export function toModule(file, src) {
  const names = [];
  let body = src
    .replace(/^import \* as (\w+) from "\.\/([\w-]+\.js)";$/gm, (_m, ns, p) => `const ${ns} = __req("${p}");`)
    .replace(/^import \{([^}]+)\} from "\.\/([\w-]+\.js)";$/gm, (_m, list, p) => `const {${list.replace(/\s+as\s+/g, ": ")}} = __req("${p}");`)
    .replace(/^export (async function|function|class|const|let) ([\w$]+)/gm, (_m, kw, n) => { names.push(n); return `${kw} ${n}`; });
  if (/^\s*(import|export)\b/m.test(body)) throw new Error(`${file}: an import or export form the bundler does not handle`);
  return `__def("${file}", function (exports, __req) {\n${body.trim()}\nObject.assign(exports, { ${names.join(", ")} });\n});`;
}

/** Joins modules (file names in public/cw/js) and an entry into one classic script. */
export function bundle(files, entry) {
  const mods = files.map((f) => toModule(f, read(join(SRC, "js", f))));
  return `/* RoboValley contribution workflow - GENERATED by scripts/build-contribution-workflow.mjs from public/cw/js (${files.join(", ")}). Do not edit. */
(function () {
"use strict";
var __mods = {}, __cache = {};
function __def(name, fn) { __mods[name] = fn; }
function __req(name) { if (__cache[name]) return __cache[name]; var e = {}; __cache[name] = e; __mods[name](e, __req); return e; }
${mods.join("\n")}
${entry}
})();
`;
}

const has = (f) => existsSync(join(SRC, "js", f));
const BASE = ["lists.js", "utils.js", "rules.js", "api.js", "card.js"];

/** The WordPress script: the public screens only (the form, and Community Ideas once it exists). */
export function pluginScript() {
  const screens = ["form.js", "site.js"].filter(has);
  const mounts = screens.map((f) => `  if (kind === "${f.replace(".js", "")}") __req("${f}").mount(el);`).join("\n");
  return bundle([...BASE, ...screens], `function start() {
  Array.prototype.forEach.call(document.querySelectorAll("[data-rv-cw]"), function (el) {
    if (el.getAttribute("data-rv-cw-ready")) return;
    el.setAttribute("data-rv-cw-ready", "1");
    var kind = el.getAttribute("data-rv-cw");
${mounts}
  });
}
if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start); else start();`);
}

/** The sector pages' script (sector-buttons.php loads it): the header button and a button on every field, kept there. */
export function sectorScript() {
  return bundle(["utils.js", "fields.js", "sector.js"], `function go() {
  var cfg = window.rvContribFields || {};
  if (cfg.started) return;
  cfg.started = true;
  var h = __req("sector.js").startSectorPage(cfg, document);
  cfg.refresh = h.refresh; // for a plugin that wants its new field handled at once (it is handled anyway on the next change)
  window.rvContribFields = cfg;
}
if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", go); else go();`);
}

