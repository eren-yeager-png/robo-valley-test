/** The WordPress script: the public screens only (the form, and Community Ideas once it exists). */
export function pluginScript() {
  const screens = ["form.js", "site.js"].filter(has);
  const mounts = screens.map((f) => `  if (kind === "${f.replace(".js", "")}") __req("${f}").mount(el);`).join("\n");
  return bundle([...BASE, ...screens], `function start() {
  Array.prototype.forEach.call(document.querySelectorAll("[data-rv-cw]"), function (el) {
    if (el.getAttribute("data-rv-cw-ready")) return;
    el.setAttribute("data-rv-cw-ready", "1");
    var kind = el.getAttribute("data-rv-cw");
${mounts}
  });
}
if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", start); else start();`);
}

